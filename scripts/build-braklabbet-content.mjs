// Bundles the Bråklabbet student source into one self-contained HTML string
// served only by the auth-checked braklabbet-content edge function.
import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../supabase/functions/braklabbet-content/", import.meta.url);
const read = (f) => readFileSync(new URL("source/" + f, dir), "utf8");
const math = read("math.js").replace(/^export\s+/gm, "");
const app = read("app.js").replace(/^import\s*\{[^}]*\}\s*from\s*['"]\.\/math\.js['"];?\s*$/m, "");
const exercises = read("comparison-exercises.js").replace(/^export\s+/gm, "");
writeFileSync(new URL("../_shared/braklabbet-exercises.js", dir), "// GENERATED from protected lab source by build-braklabbet-content.mjs\n" + read("comparison-exercises.js"));
const training = read("training.js").replace(/^import[^\n]*\n/, "");
if (/^\s*(import|export)\s/m.test(math + app + exercises + training)) throw new Error("module syntax left in bundle");
const csp = "default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'";
let html = read("index.html")
  .replace(/\s*<link rel="icon"[^>]*>/, "")
  .replace(/<link rel="stylesheet" href="\/styles\.css">/, () => `<meta http-equiv="Content-Security-Policy" content="${csp}">\n<style>\n${read("styles.css")}\n</style>`)
  .replace(/<script type="module" src="\/app\.js"><\/script>/, () => `<script type="module">\n${math}\n${(app + '\n' + exercises + '\n' + training).replace(/<\/script/gi, "<\\/script")}\n</script>`);
if (html.includes('src="/app.js"') || html.includes('href="/styles.css"')) throw new Error("bundle replace failed");
writeFileSync(new URL("content.ts", dir), `// GENERATED by scripts/build-braklabbet-content.mjs — do not edit by hand.\nexport const BRAKLABBET_HTML: string = ${JSON.stringify(html)};\n`);
console.log("wrote content.ts", html.length);
